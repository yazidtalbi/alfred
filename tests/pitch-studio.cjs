const assert = require('node:assert/strict');
const pitch = require('../pitch-studio/core.js');
const sample={name:'Maison Atlas',audience:'Luxury home buyers',solution:'A responsive, cinematic property browsing experience',industry:'real estate',website:'https://example.com',creator:'Arlibera'};
assert.equal(pitch.validate(sample).errors.length,0,'valid brief');
assert.equal(pitch.deck(sample).length,6,'six presentation slides');
assert.equal(pitch.storyboard(sample).length,6,'six storyboard scenes');
assert.equal(pitch.storyboard(sample)[5].end,48,'48-second film brief');
assert.match(pitch.videoPrompt(sample),/Do not fabricate/,'no fabricated proof');
assert.match(pitch.storyboardText(sample),/Storyboard only/,'explicit rendering limitation');
assert.match(pitch.exportHtml(sample),/<!doctype html>/,'printable deck');
assert.match(pitch.exportHtml({...sample,name:'<script>alert("x")</script>'}),/&lt;script&gt;/,'HTML escaping');
assert.equal(pitch.publicUrl('http://localhost:3000'),'', 'no localhost URL');
assert.equal(pitch.publicUrl('http://192.168.1.2'),'', 'no private IPv4');
assert.equal(pitch.publicUrl('file:///etc/passwd'),'', 'no non-http schemes');
assert.ok(pitch.publicUrl('https://example.com'), 'public website URL');
assert.ok(pitch.validate({...sample,website:'file:///etc/passwd'}).errors.length, 'bad URL rejected');
assert.equal(pitch.normalize({...sample,audit:{url:'https://different.example',scores:{SEO:20}}}).audit,null, 'stale audit detached');
assert.match(pitch.deck({...sample,language:'fr'})[0].eyebrow,/proposition/i,'French variant');
console.log('Passed: Pitch Studio core, six-slide deck, storyboard, safety and HTML export.');
